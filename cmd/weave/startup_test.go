func TestCompileBuildsOwnerToolBeforeLeafGenerator(t *testing.T) {
	root := t.TempDir()
	base, leaf := filepath.Join(root, "base"), filepath.Join(root, "leaf")
	write := func(path, body string) {
		t.Helper()
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0755); err != nil {
			t.Fatal(err)
		}
	}
	write(filepath.Join(base, "construct/base.manifest"), "skill construct/local\n")
	write(filepath.Join(leaf, "construct/deps"), "substrate ../base\n")
	write(filepath.Join(base, "generator"), "#!/bin/sh\nmkdir -p \"$1\"\nprintf '%s\\n' '---' 'name: example' 'description: built generator' '---' 'GENERATED BY OWNER TOOL' > \"$1/SKILL.md\"\n")
	write(filepath.Join(base, "Makefile"), "tools:\n\tmkdir -p bin\n\tcp generator bin/fixture-generator\n")
	write(filepath.Join(base, "construct/local/example/.dynamic-skill"), "#!/bin/sh\n# weave-output: argv1\nfixture-generator \"$1\"\n")
	var out bytes.Buffer
	if err := run(weavefs.OSFS{}, leaf, plan.TargetAll, false, &out); err != nil {
		t.Fatal(err, out.String())
	}
	got, err := os.ReadFile(filepath.Join(leaf, ".agents/skills/base-example/SKILL.md"))
	if err != nil || !strings.Contains(string(got), "GENERATED BY OWNER TOOL") {
		t.Fatalf("generated skill = %q, %v", got, err)
	}
	if _, err := os.Stat(filepath.Join(base, "construct/generated/example")); !os.IsNotExist(err) {
		t.Fatalf("generator wrote to base: %v", err)
	}
	if !strings.Contains(out.String(), filepath.Join(base, "bin")) {
		t.Fatalf("missing shell PATH guidance: %s", out.String())
	}
	if err := run(weavefs.OSFS{}, leaf, plan.TargetAll, false, &out); err != nil {
		t.Fatal("repeat:", err)
	}
}

